import { describe, expect, it } from "vitest"
import { snap } from "./geometry"
import type { Point, Wall } from "./types"

// change ortho-stretch-move, wall-selection «Орто без боковой составляющей» (design D1):
// при сработавшей орто-привязке точка лежит строго на оси через опорную точку; стены и сетка
// действуют только вдоль оси. Без срабатывания орто — прежнее поведение.

const W = (ax: number, ay: number, bx: number, by: number): Wall => ({
  id: `o${ax}_${ay}_${bx}_${by}`,
  a: { x: ax, y: ay },
  b: { x: bx, y: by },
  thicknessCm: 20,
  type: "brick",
})

const GRID = 10
const R = 5
const tan = (deg: number): number => Math.tan((deg * Math.PI) / 180)

describe("snap при орто: точка на оси", () => {
  it("OS-1: опорная точка вне сетки, тянем почти вертикально — x не меняется, y по сетке", () => {
    expect(snap({ x: 7, y: -23 }, [], GRID, R, { x: 5, y: 15 })).toEqual({ x: 5, y: -20 })
  })

  it("OS-2: опорная точка вне сетки, тянем почти горизонтально — y не меняется, x по сетке", () => {
    expect(snap({ x: 263, y: 17 }, [], GRID, R, { x: 0, y: 15 })).toEqual({ x: 260, y: 15 })
  })

  it("OS-3: линия вертикальной стены в радиусе — пересечение оси с линией стены", () => {
    expect(snap({ x: 97, y: 18 }, [W(100, -100, 100, 100)], GRID, R, { x: 0, y: 15 })).toEqual({ x: 100, y: 15 })
  })

  it("OS-4: параллельная стена рядом с осью игнорируется — точка остаётся на оси, по сетке", () => {
    expect(snap({ x: 150, y: 17 }, [W(0, 19, 300, 19)], GRID, R, { x: 0, y: 15 })).toEqual({ x: 150, y: 15 })
  })

  it("OS-5: конец стены в радиусе — его проекция на ось", () => {
    expect(snap({ x: 201, y: 16 }, [W(180, 20, 203, 20)], GRID, R, { x: 0, y: 15 })).toEqual({ x: 203, y: 15 })
  })

  it("OS-8: две стены пересекают ось в радиусе — ближайшая к курсору", () => {
    const walls = [W(98, -100, 98, 100), W(103, -100, 103, 100)]
    expect(snap({ x: 101, y: 16 }, walls, GRID, R, { x: 0, y: 15 })).toEqual({ x: 103, y: 15 })
  })

  it("OS-9: вертикальная ось и горизонтальная стена", () => {
    expect(snap({ x: 17, y: 97 }, [W(-100, 100, 100, 100)], GRID, R, { x: 15, y: 5 })).toEqual({ x: 15, y: 100 })
  })

  it("OS-11: пересечение оси с продолжением линии стены за её концом (концы вне радиуса)", () => {
    // линия стены (90,-100)–(95,-50) пересекает ось y = 15 в x = 101.5 — за концом отрезка
    expect(snap({ x: 101, y: 16 }, [W(90, -100, 95, -50)], GRID, R, { x: 0, y: 15 })).toEqual({ x: 101.5, y: 15 })
  })

  it("OS-10: стены вне радиуса — сетка только вдоль оси", () => {
    expect(snap({ x: 147, y: 18 }, [W(0, 100, 300, 100)], GRID, R, { x: 3, y: 15 })).toEqual({ x: 150, y: 15 })
  })
})

describe("snap при орто: граница срабатывания", () => {
  it("OS-6: 30° от горизонтали — орто не срабатывает, привязка к сетке по обеим координатам", () => {
    expect(snap({ x: 52, y: 30 }, [], GRID, R, { x: 0, y: 0 })).toEqual({ x: 50, y: 30 })
  })

  it("OS-6b: 14.5° — на оси; 16° — по обеим координатам", () => {
    expect(snap({ x: 100, y: 3 + 100 * tan(14.5) }, [], GRID, R, { x: 0, y: 3 })).toEqual({ x: 100, y: 3 })
    const off = snap({ x: 100, y: 3 + 100 * tan(16) }, [], GRID, R, { x: 0, y: 3 })
    expect(off).toEqual({ x: 100, y: 30 })
  })

  it("OS-7: без опорной точки — прежнее поведение (стена с приоритетом, иначе сетка)", () => {
    expect(snap({ x: 150, y: 17 }, [W(0, 19, 300, 19)], GRID, R)).toEqual({ x: 150, y: 19 })
    expect(snap({ x: 147, y: 18 }, [], GRID, R)).toEqual({ x: 150, y: 20 })
  })
})

describe("snap при орто: инвариант оси", () => {
  // INV-AXIS: координата поперёк оси равна координате опорной точки при любых стенах рядом
  const from: Point = { x: 3.7, y: 15.3 }
  const scenes: Wall[][] = [[], [W(0, 19, 300, 19)], [W(100, -100, 100, 100)], [W(180, 20, 203, 20)], [W(0, 10, 300, 30)]]
  it("OS-INV: горизонтальная ось — y точно как у опорной точки", () => {
    for (const walls of scenes)
      for (const x of [21, 97, 148, 201, 263]) expect(snap({ x, y: from.y + 2 }, walls, GRID, R, from).y).toBe(from.y)
  })
  it("OS-INV: вертикальная ось — x точно как у опорной точки", () => {
    for (const walls of scenes)
      // все точки в пределах 15° от вертикали через опорную точку (|dy| ≥ 14.7 при dx = 1)
      for (const y of [-63, 30, 97, 140]) expect(snap({ x: from.x + 1, y }, walls, GRID, R, from).x).toBe(from.x)
  })
})
